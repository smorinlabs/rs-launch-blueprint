#!/usr/bin/env bash
# R15 empirical check — runs every case against the synthetic Rust fixture.
# Usage: run-checks.sh host|linux
#   host  : macOS, uses ./venv       (uv venv venv --python 3.13; uv pip install template-press==4.0.1)
#   linux : Ubuntu VM, uses ./venv-linux (same recipe, created by run-linux-leg.sh)
# Each case writes review/evidence/<case>-<leg>.log and prints "CASE <name> exit=<n> expect=<m>".
set -u
LEG="${1:-host}"
E="$(cd "$(dirname "$0")" && pwd)"
EVID="${EVID:-$E/../evidence}"   # overridden by run-linux-leg.sh (read-only mount in the VM)
VENV="$E/venv"; [ "$LEG" = linux ] && VENV="$E/venv-linux"
PRESS="$VENV/bin/press"
WORK="$E/work-$LEG"
export CARGO_TARGET_DIR="$E/target-$LEG"
export CARGO_TERM_COLOR=never
rm -rf "$WORK"; mkdir -p "$WORK" "$EVID"
SUMMARY="$EVID/summary-$LEG.log"
: > "$SUMMARY"

hdr() {
  echo "# R15 empirical check — leg=$LEG — $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# os: $(uname -srm)"; [ "$LEG" = host ] && sw_vers 2>/dev/null | tr '\n' ' ' && echo
  echo "# rustc: $(rustc --version) | cargo: $(cargo --version)"
  echo "# floor: $(rustup run 1.96.0 rustc --version 2>&1) | $(rustup run 1.96.0 cargo --version 2>&1)"
  echo "# uv: $(uv --version) | press: $("$PRESS" --version 2>&1)"
  echo "# python: $("$VENV/bin/python" --version 2>&1)"
}
record() { # record <case> <exit> <expect>
  echo "CASE $1 exit=$2 expect=$3" | tee -a "$SUMMARY"
}
mk_copy() { # mk_copy <name> -> fresh git repo copy of the fixture at $WORK/<name>
  rm -rf "$WORK/$1"; cp -R "$E/fixture" "$WORK/$1"
  ( cd "$WORK/$1" && git init -q -b main . && git remote add origin https://github.com/smorinlabs/rs-launch-blueprint.git \
    && git add -A && git -c user.name=fixture -c user.email=fixture@example.com commit -qm "fixture" ) 
}

# ---------- 1. clean target: verify (zero-arg, --target, --json) and check-tools
{
  hdr
  mk_copy clean; cd "$WORK/clean"
  echo "\$ cd work-$LEG/clean && press verify"; "$PRESS" verify; rc=$?; echo "exit=$rc"; record verify-clean $rc 0
  echo "\$ press verify --target work-$LEG/clean --json"; "$PRESS" verify --target "$WORK/clean" --json; echo "exit=$?"
  echo "\$ press check-tools --target work-$LEG/clean"; "$PRESS" check-tools --target "$WORK/clean"; rc=$?; echo "exit=$rc"; record check-tools $rc 0
  echo "\$ git status --porcelain (must be empty: verify never mutates the target)"; git status --porcelain; echo "(end)"
} > "$EVID/verify-clean-$LEG.log" 2>&1

# ---------- 2. planted leak: identity in a file the rules exclude from rewrite
{
  hdr
  mk_copy leak; cd "$WORK/leak"
  mkdir -p docs
  printf '# Notes\n\nGenerated by rs-launch-blueprint (rslbp); call rs_launch_blueprint::run.\n' > docs/NOTES.md
  # declare the file excluded from rewrite, directly under the existing [rules] header
  awk '{print} /^\[rules\]$/{print "extra_exclude_files = [\"docs/NOTES.md\"]"}' press/press-rules.toml > press/press-rules.toml.new \
    && mv press/press-rules.toml.new press/press-rules.toml
  git add -A && git -c user.name=fixture -c user.email=fixture@example.com commit -qm "plant leak"
  echo "--- docs/NOTES.md"; cat docs/NOTES.md; echo "--- press/press-rules.toml [rules]"; sed -n '1,8p' press/press-rules.toml
  echo "\$ press verify"; "$PRESS" verify; rc=$?; echo "exit=$rc"; record verify-leak $rc 1
} > "$EVID/verify-leak-$LEG.log" 2>&1

# ---------- 3. stale package_name (undiscoverable and absent) -> 2
{
  hdr
  mk_copy stale; cd "$WORK/stale"
  sed -i.bak 's/^package_name = "rs_launch_blueprint"/package_name = "rs_launch_blueprint_core"/' press/press-source.toml && rm press/press-source.toml.bak
  git add -A && git -c user.name=fixture -c user.email=fixture@example.com commit -qm "stale package_name"
  echo "--- press/press-source.toml"; cat press/press-source.toml
  echo "\$ press verify"; "$PRESS" verify; rc=$?; echo "exit=$rc"; record verify-stale-package-name $rc 2
} > "$EVID/verify-stale-package-name-$LEG.log" 2>&1

# ---------- 4. wrong owner (git-origin-derived, genuinely cross-checked) -> 2
{
  hdr
  mk_copy owner; cd "$WORK/owner"
  sed -i.bak 's/^owner        = "smorinlabs"/owner        = "wrongowner"/' press/press-source.toml && rm press/press-source.toml.bak
  git add -A && git -c user.name=fixture -c user.email=fixture@example.com commit -qm "wrong owner"
  echo "--- press/press-source.toml"; cat press/press-source.toml
  echo "\$ press verify"; "$PRESS" verify; rc=$?; echo "exit=$rc"; record verify-wrong-owner $rc 2
} > "$EVID/verify-wrong-owner-$LEG.log" 2>&1

# ---------- 5. Codex's proposed field names (crate_name/binary_name + [verify].extra_fields)
{
  hdr
  mk_copy codexfields; cd "$WORK/codexfields"
  cat > press/press-source.toml <<'T'
[identity]
package_name = "rs-launch-blueprint"
crate_name   = "rs_launch_blueprint"
binary_name  = "rslbp"
repo_name    = "rs-launch-blueprint"
app_name     = "rslbp"
owner        = "smorinlabs"
display_name = "Rs Launch Blueprint"
T
  printf '\n[verify]\nextra_fields = ["crate_name", "binary_name"]\n' >> press/press-rules.toml
  git add -A && git -c user.name=fixture -c user.email=fixture@example.com commit -qm "codex field names"
  echo "--- press/press-source.toml"; cat press/press-source.toml
  echo "--- press/press-rules.toml tail"; tail -n 4 press/press-rules.toml
  echo "\$ press verify"; "$PRESS" verify; rc=$?; echo "exit=$rc"; record verify-codex-field-names $rc observe
} > "$EVID/verify-codex-field-names-$LEG.log" 2>&1

# ---------- 6. display_name omitted (is the 7th field optional?)
{
  hdr
  mk_copy sixfields; cd "$WORK/sixfields"
  sed -i.bak '/^display_name/d' press/press-source.toml && rm press/press-source.toml.bak
  git add -A && git -c user.name=fixture -c user.email=fixture@example.com commit -qm "six fields"
  echo "--- press/press-source.toml"; cat press/press-source.toml
  echo "\$ press verify"; "$PRESS" verify; rc=$?; echo "exit=$rc"; record verify-six-fields $rc observe
} > "$EVID/verify-six-fields-$LEG.log" 2>&1

# ---------- 7. real press of a copy -> receipt -> guard fires -> pressed copy builds and tests
{
  hdr
  mk_copy pressed; cd "$WORK/pressed"
  cat > "$WORK/answers.toml" <<'T'
[answers]
package_name = "zz_pressed"
repo_name    = "zz-pressed"
app_name     = "zzp"
author       = "Zed Example"
email        = "zz@example.com"
owner        = "zz-owner"
display_name = "Zz Pressed"
T
  echo "--- answers.toml"; cat "$WORK/answers.toml"
  echo "\$ press rebrand --target work-$LEG/pressed --config work-$LEG/answers.toml"
  "$PRESS" rebrand --target "$WORK/pressed" --config "$WORK/answers.toml"; rc=$?; echo "exit=$rc"; record rebrand $rc 0
  echo "\$ test -f press/press-receipt.toml"; test -f press/press-receipt.toml; echo "exit=$?"
  echo "--- press/press-receipt.toml"; cat press/press-receipt.toml 2>&1
  echo "--- press/press-source.toml (after press)"; cat press/press-source.toml
  echo "--- Cargo.toml (after press)"; cat Cargo.toml
  echo "--- workflow files present after press (template-receipt-guard.yml must be gone)"; ls .github/workflows
  echo "--- old identity outside the receipt (expect none):"; grep -rIn -e rs-launch-blueprint -e rs_launch_blueprint -e rslbp -e RSLBP --exclude=press-receipt.toml --exclude-dir=.git --exclude-dir=target . ; echo "grep exit=$? (1 = no match)"
  echo "\$ bash .github/receipt-guard-body.sh   (in the pressed copy: receipt present)"
  bash .github/receipt-guard-body.sh; rc=$?; echo "exit=$rc"; record receipt-guard-with-receipt $rc 1
  echo "\$ cargo test --workspace   (in the pressed copy)"
  cargo test --workspace 2>&1; rc=$?; echo "exit=$rc"; record pressed-copy-cargo-test $rc 0
} > "$EVID/rebrand-and-receipt-guard-$LEG.log" 2>&1

# ---------- 8. guard on the clean template -> 0
{
  hdr
  cd "$WORK/clean"
  echo "\$ bash .github/receipt-guard-body.sh   (clean template: no receipt)"
  bash .github/receipt-guard-body.sh; rc=$?; echo "exit=$rc"; record receipt-guard-clean $rc 0
} > "$EVID/receipt-guard-clean-$LEG.log" 2>&1

# ---------- 9. compensating control: cargo metadata cross-check, stable and floor 1.96.0
{
  hdr
  cd "$WORK/clean"
  echo "\$ cargo test --test press_source   (stable)"; cargo test --test press_source 2>&1; rc=$?; echo "exit=$rc"; record press-source-test-stable $rc 0
  FLOOR="$(rustup run 1.96.0 rustc --print sysroot)/bin"
  echo "\$ PATH=$FLOOR:\$PATH cargo test --test press_source   (floor 1.96.0)"
  PATH="$FLOOR:$PATH" cargo --version; PATH="$FLOOR:$PATH" cargo test --test press_source 2>&1; rc=$?; echo "exit=$rc"; record press-source-test-floor $rc 0
  mk_copy drift; cd "$WORK/drift"
  sed -i.bak 's/^name = "rslbp"/name = "rslb"/' Cargo.toml && rm Cargo.toml.bak
  echo "--- Cargo.toml [[bin]] after drift"; grep -n -A2 '^\[\[bin\]\]' Cargo.toml
  echo "\$ cargo test --test press_source   (drifted bin name, stable)"; cargo test --test press_source 2>&1; rc=$?; echo "exit=$rc"; record press-source-test-drift-stable $rc 101
  echo "\$ PATH=$FLOOR:\$PATH cargo test --test press_source   (drifted bin name, floor 1.96.0)"
  PATH="$FLOOR:$PATH" cargo test --test press_source 2>&1; rc=$?; echo "exit=$rc"; record press-source-test-drift-floor $rc 101
} > "$EVID/press-source-cross-check-$LEG.log" 2>&1

# ---------- 10. the recommended workflow lines exactly as written in press-verify.yml
{
  hdr
  mk_copy wf; cd "$WORK/wf"
  echo "--- the three run: lines from .github/workflows/press-verify.yml"; grep -n -A3 'run: |' .github/workflows/press-verify.yml
  echo "\$ uv venv --python 3.13"; uv venv --python 3.13 2>&1; echo "exit=$?"
  echo "\$ uv pip sync press/requirements.txt"; uv pip sync press/requirements.txt 2>&1; echo "exit=$?"
  echo "\$ uv run press verify"; uv run press verify 2>&1; rc=$?; echo "exit=$rc"; record workflow-lines $rc 0
  echo "\$ git status --porcelain (.venv is ignored; tree unchanged)"; git status --porcelain; echo "(end)"
} > "$EVID/workflow-lines-$LEG.log" 2>&1

echo "=== summary ($LEG)"; cat "$SUMMARY"
