#!/usr/bin/env bash
# shellcheck disable=SC2016
#   SC2016 is disabled file-wide and deliberately: every single-quoted
#   search string below is a literal quotation of a source file, a
#   registry cell or a compiler message, and the backticks, `$` signs and
#   Markdown emphasis inside them must NOT expand. Single quotes are the
#   point, not an oversight.
#
# R03 port-absence-vs-failure-contract — synthesizer check 2 of 3.
#
# Verifies the type-level claims the raw reports make about the recommended
# shape, in a throwaway crate built OUTSIDE this repository under $TMPDIR and
# deleted when the script exits. It implements none of the template: no real
# adapter, no HTTP, no CLI, no envelope writer, no async. The crate exists only
# so the compiler can answer four questions that cannot be answered by reading:
#
#   P1  Does `Ok(None)` from the seam reach the use case as a domain not-found
#       carrying the offending input, with no `source()`?
#   P2  Does a transport failure keep its cause chain across `?` through
#       `#[from]` + `#[error(transparent)]`?
#   P3  Is an empty collection read distinguishable from absence?
#   P4  Does OMITTING the use case's absence translation fail to COMPILE — and
#       with which compiler error?
#
# Determinism contract
# --------------------
#   * The crate is generated by this script, so it is identical on every run.
#     `thiserror` is pinned `=2.0.20` and cargo runs `--offline`, so no version
#     resolution and no network reach the result.
#   * Machine-dependent text (toolchain versions, OS, the $TMPDIR path, cargo's
#     wall-clock timings) is written to ./toolchain.txt, never to stdout. Only
#     asserted lines are echoed, filtered by fixed-string match. So
#     `bash r03-probe.sh | diff - r03-probe.log` is empty on any rerun with the
#     same toolchain.
#   * Without cargo, or without `thiserror` 2.0.20 in the local registry cache,
#     the script prints `SKIP` with the reason instead of failing.
#
# Usage: bash r03-probe.sh             (run from anywhere)

set -uo pipefail

GREP=/usr/bin/grep
HERE=$(cd -- "$(dirname -- "$0")" && pwd)
EVID="$HERE"

FAILED=0
section() { printf '\n========== %s ==========\n' "$1"; }
claim()   { printf '\n--- %s ---\n' "$1"; }
skip()    { printf 'SKIP %s — %s\n' "$1" "$2"; }

assert() {
  if [ "$2" = "$3" ]; then
    printf 'PASS %s (expected %s, got %s; binary: %s)\n' "$1" "$2" "$3" "$GREP"
  else
    printf 'FAIL %s (expected %s, got %s; binary: %s)\n' "$1" "$2" "$3" "$GREP"
    FAILED=$((FAILED + 1))
  fi
}

count() { $GREP -c -F -- "$2" "$1" 2>/dev/null || true; }

section '0. Toolchain'

if ! command -v cargo > /dev/null 2>&1 || ! command -v rustc > /dev/null 2>&1; then
  skip 'probe' 'no cargo/rustc on PATH'
  printf '\n========== RESULT ==========\nSKIPPED (no toolchain)\n'
  exit 0
fi

{
  printf 'rustc: %s\n' "$(rustc --version)"
  printf 'cargo: %s\n' "$(cargo --version)"
  printf 'uname: %s\n' "$(uname -srm)"
  printf 'macOS ProductVersion: %s\n' "$(sw_vers -productVersion 2> /dev/null || echo 'n/a')"
  printf 'probe manifest: edition = "2024", rust-version = "1.96", thiserror = "=2.0.20"\n'
  printf 'probe location: a mktemp -d directory under $TMPDIR, deleted on exit\n'
} > "$EVID/toolchain.txt"
printf 'toolchain and platform written to ./toolchain.txt (kept off stdout so reruns diff clean)\n'

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
CRATE="$WORK/absence_probe"
mkdir -p "$CRATE/src" "$CRATE/tests"

cat > "$CRATE/Cargo.toml" <<'TOML'
[package]
name = "absence_probe"
version = "0.0.0"
edition = "2024"
rust-version = "1.96"
publish = false

[dependencies]
thiserror = "=2.0.20"
TOML

# ---------------------------------------------------------------------------
# The probe library. Stand-ins only: ErrorCode/Exit are minimal shapes standing
# in for R67's real ones, sufficient to prove routing and nothing more.
# ---------------------------------------------------------------------------
cat > "$CRATE/src/lib.rs" <<'RS'
use std::sync::{Arc, Mutex};

#[derive(Debug, Clone, PartialEq)]
pub struct Project {
    pub id: String,
}

/// Stand-in for R67's catalogue enum (append-only, `#[non_exhaustive]`).
#[non_exhaustive]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ErrorCode {
    Io,
    Transport,
    RemoteApi,
    CredentialsRejected,
    Conflict,
    NotFound,
}

impl ErrorCode {
    pub const fn as_str(&self) -> &'static str {
        match self {
            ErrorCode::Io => "RSLB101",
            ErrorCode::Transport => "RSLB102",
            ErrorCode::RemoteApi => "RSLB103",
            ErrorCode::CredentialsRejected => "RSLB402",
            ErrorCode::Conflict => "RSLB501",
            ErrorCode::NotFound => "RSLB301",
        }
    }

    pub const fn exit(&self) -> u8 {
        match self {
            ErrorCode::Io | ErrorCode::Transport | ErrorCode::RemoteApi => 1,
            ErrorCode::NotFound => 3,
            ErrorCode::CredentialsRejected => 4,
            ErrorCode::Conflict => 5,
        }
    }
}

/// Transport vocabulary only. There is deliberately no `NotFound` variant.
#[non_exhaustive]
#[derive(Debug, thiserror::Error)]
pub enum PortError {
    #[error("local I/O failed")]
    Io {
        #[source]
        source: std::io::Error,
    },
    #[error("transport failed")]
    Transport {
        #[source]
        source: Box<dyn std::error::Error + Send + Sync + 'static>,
    },
    #[error("remote API failed")]
    RemoteApi {
        #[source]
        source: Box<dyn std::error::Error + Send + Sync + 'static>,
    },
    #[error("credentials rejected")]
    Unauthorized {
        #[source]
        source: Box<dyn std::error::Error + Send + Sync + 'static>,
    },
    #[error("conflict")]
    Conflict {
        #[source]
        source: Box<dyn std::error::Error + Send + Sync + 'static>,
    },
    #[error("adapter unavailable: {detail}")]
    Unavailable { detail: String },
}

impl PortError {
    pub const fn code(&self) -> ErrorCode {
        match self {
            PortError::Io { .. } | PortError::Unavailable { .. } => ErrorCode::Io,
            PortError::Transport { .. } => ErrorCode::Transport,
            PortError::RemoteApi { .. } => ErrorCode::RemoteApi,
            PortError::Unauthorized { .. } => ErrorCode::CredentialsRejected,
            PortError::Conflict { .. } => ErrorCode::Conflict,
        }
    }
}

#[non_exhaustive]
#[derive(Debug, thiserror::Error)]
pub enum DomainError {
    #[error("{kind} '{id}' not found")]
    NotFound { kind: &'static str, id: String },
    #[error(transparent)]
    Port(#[from] PortError),
}

impl DomainError {
    pub const fn code(&self) -> ErrorCode {
        match self {
            DomainError::NotFound { .. } => ErrorCode::NotFound,
            DomainError::Port(e) => e.code(),
        }
    }
}

/// R01's seam shape, carrying this item's absence contract.
pub trait ProjectsPort: Send + Sync {
    /// `Ok(None)` means the upstream authoritatively has no such project.
    fn get(&self, id: &str) -> Result<Option<Project>, PortError>;
    /// An empty `Vec` is a complete answer, never an absence.
    fn list(&self) -> Result<Vec<Project>, PortError>;
}

impl<T: ProjectsPort + ?Sized> ProjectsPort for Arc<T> {
    fn get(&self, id: &str) -> Result<Option<Project>, PortError> {
        (**self).get(id)
    }
    fn list(&self) -> Result<Vec<Project>, PortError> {
        (**self).list()
    }
}

/// A programmable fake. Not the template's `InMemoryProjectsPort`.
pub struct FakePort {
    pub rows: Mutex<Vec<Project>>,
    pub fail_with: Mutex<Option<fn() -> PortError>>,
}

impl FakePort {
    pub fn with(ids: &[&str]) -> Self {
        FakePort {
            rows: Mutex::new(ids.iter().map(|i| Project { id: (*i).to_owned() }).collect()),
            fail_with: Mutex::new(None),
        }
    }
    pub fn failing(f: fn() -> PortError) -> Self {
        FakePort { rows: Mutex::new(Vec::new()), fail_with: Mutex::new(Some(f)) }
    }
}

impl ProjectsPort for FakePort {
    fn get(&self, id: &str) -> Result<Option<Project>, PortError> {
        if let Some(f) = *self.fail_with.lock().unwrap() {
            return Err(f());
        }
        Ok(self.rows.lock().unwrap().iter().find(|p| p.id == id).cloned())
    }
    fn list(&self) -> Result<Vec<Project>, PortError> {
        if let Some(f) = *self.fail_with.lock().unwrap() {
            return Err(f());
        }
        Ok(self.rows.lock().unwrap().clone())
    }
}

pub struct ProjectsService<P: ProjectsPort> {
    pub port: P,
}

impl<P: ProjectsPort> ProjectsService<P> {
    /// The only translation site in the crate.
    pub fn get_project(&self, id: &str) -> Result<Project, DomainError> {
        self.port
            .get(id)?
            .ok_or_else(|| DomainError::NotFound { kind: "project", id: id.to_owned() })
    }
    pub fn list_projects(&self) -> Result<Vec<Project>, DomainError> {
        Ok(self.port.list()?)
    }
}

pub fn chain(e: &dyn std::error::Error) -> Vec<String> {
    let mut out = vec![e.to_string()];
    let mut cur = e.source();
    while let Some(c) = cur {
        out.push(c.to_string());
        cur = c.source();
    }
    out
}
RS

cat > "$CRATE/tests/absence_vs_failure.rs" <<'RS'
use absence_probe::*;
use std::error::Error;
use std::sync::Arc;

fn svc(port: FakePort) -> ProjectsService<Arc<dyn ProjectsPort>> {
    ProjectsService { port: Arc::new(port) as Arc<dyn ProjectsPort> }
}

#[test]
fn present_is_ok() {
    let s = svc(FakePort::with(&["demo"]));
    assert_eq!(s.get_project("demo").unwrap().id, "demo");
}

#[test]
fn absence_is_rslb301_exit3_names_the_input_and_has_no_source() {
    let s = svc(FakePort::with(&["other"]));
    let e = s.get_project("demo").unwrap_err();
    assert_eq!(e.code().as_str(), "RSLB301");
    assert_eq!(e.code().exit(), 3);
    assert_eq!(e.to_string(), "project 'demo' not found");
    assert!(e.source().is_none(), "absence has no transport cause");
}

#[test]
fn transport_failure_is_rslb102_exit1_and_keeps_its_cause_chain() {
    let s = svc(FakePort::failing(|| PortError::Transport {
        source: Box::new(std::io::Error::new(std::io::ErrorKind::TimedOut, "connect timed out")),
    }));
    let e = s.get_project("demo").unwrap_err();
    assert_eq!(e.code().as_str(), "RSLB102");
    assert_eq!(e.code().exit(), 1);
    assert_eq!(chain(&e), vec!["transport failed", "connect timed out"]);
}

#[test]
fn local_io_failure_is_rslb101_exit1() {
    let s = svc(FakePort::failing(|| PortError::Io {
        source: std::io::Error::new(std::io::ErrorKind::PermissionDenied, "denied"),
    }));
    let e = s.get_project("demo").unwrap_err();
    assert_eq!(e.code().as_str(), "RSLB101");
    assert_eq!(e.code().exit(), 1);
}

#[test]
fn unavailable_adapter_state_is_a_failure_not_an_absence() {
    let s = svc(FakePort::failing(|| PortError::Unavailable { detail: "poisoned".into() }));
    let e = s.get_project("demo").unwrap_err();
    assert_eq!(e.code().as_str(), "RSLB101");
    assert_eq!(e.code().exit(), 1);
    assert_ne!(e.code().as_str(), "RSLB301");
}

#[test]
fn empty_list_is_success_not_absence() {
    let s = svc(FakePort::with(&[]));
    assert_eq!(s.list_projects().unwrap(), Vec::new());
}

#[test]
fn transpose_converts_the_other_nesting() {
    let outer: Option<Result<Project, PortError>> = Some(Ok(Project { id: "demo".into() }));
    let inner: Result<Option<Project>, PortError> = outer.transpose();
    assert_eq!(inner.unwrap().unwrap().id, "demo");
}
