//! Code-first OpenAPI 3.1 contract generation, RFC 9457 problem response pass, and snapshot
//! export helpers (`R71` F307/F312/F332/F333, `R83`, `R84`).
//!
//! `info.version` is pinned to the version-independent constant [`API_DOCUMENT_VERSION`]
//! (`"0.0.0"`) so release version bumps never stale the committed `openapi/openapi.json` contract
//! (`R71` A7).

use axum::extract::State;
use axum::http::{HeaderValue, StatusCode, Uri, header};
use axum::response::{IntoResponse, Response};
use serde::Serialize;
use utoipa::openapi::content::ContentBuilder;
use utoipa::openapi::response::ResponseBuilder;
use utoipa::openapi::{OpenApi, Ref, RefOr};
use utoipa::{OpenApi as OpenApiDerive, ToSchema};

use crate::problems::{
    FieldError, PROBLEM_CONTENT_TYPE, WebError, reject_unsupported_query_params,
};
use crate::routes::ops::{LiveStatus, LivenessReport};
use crate::settings::WebSettings;

/// Document-level OpenAPI `info.version` constant decoupled from crate SemVer (`R71` A7).
pub const API_DOCUMENT_VERSION: &str = "0.0.0";

/// HTTP path serving the live OpenAPI 3.1 JSON document (`R71`, `R83`).
pub const OPENAPI_PATH: &str = "/openapi.json";

/// OpenAPI schema representation of a core `Project` (`R01`, `R71`).
///
/// Mirrors [`rs_launch_blueprint_core::Project`] without adding `utoipa` to `crates/core`.
#[derive(Debug, Clone, Serialize, ToSchema)]
#[schema(as = Project)]
pub struct ProjectSchema {
    /// Unique identifier assigned by the backing store.
    pub id: String,
    /// Human-readable project name.
    pub name: String,
    /// Optional workspace name owning this project.
    pub workspace: Option<String>,
}

/// OpenAPI schema representation of a core `CreateProjectInput` (`R01`, `R71`).
///
/// Mirrors [`rs_launch_blueprint_core::CreateProjectInput`] without adding `utoipa` to `crates/core`.
#[derive(Debug, Clone, Serialize, ToSchema)]
#[schema(as = CreateProjectInput)]
pub struct CreateProjectInputSchema {
    /// Non-empty human-readable project name.
    #[schema(min_length = 1)]
    pub name: String,
    /// Optional workspace name.
    pub workspace: Option<String>,
}

/// OpenAPI schema representation of cursor-paginated `ListResponse<Project>` (`R72`, `R71`).
#[derive(Debug, Clone, Serialize, ToSchema)]
#[schema(as = ProjectListResponse)]
pub struct ProjectListResponseSchema {
    /// Page items in deterministic ascending identifier order.
    pub items: Vec<ProjectSchema>,
    /// Opaque base64 cursor for the next page, or `null` on the final page.
    pub next_cursor: Option<String>,
}

/// OpenAPI schema representation of core `CheckStatus` (`R80`, `R71`).
#[derive(Debug, Clone, Copy, Serialize, ToSchema)]
#[schema(as = CheckStatus)]
#[serde(rename_all = "lowercase")]
pub enum CheckStatusSchema {
    /// Check passed without findings.
    Ok,
    /// Advisory finding that does not make the service unready.
    Warn,
    /// Blocking error that fails `/readyz` (`503`).
    Error,
}

/// OpenAPI schema representation of core `Check` (`R80`, `R71`).
#[derive(Debug, Clone, Serialize, ToSchema)]
#[schema(as = Check)]
pub struct CheckSchema {
    /// Stable literal check name.
    pub name: String,
    /// Outcome status (`ok`, `warn`, or `error`).
    pub status: CheckStatusSchema,
    /// Redacted human-readable check detail.
    pub detail: String,
}

/// OpenAPI schema representation of core `Diagnostics` (`R80`, `R71`).
#[derive(Debug, Clone, Serialize, ToSchema)]
#[schema(as = Diagnostics)]
pub struct DiagnosticsSchema {
    /// Executed diagnostic checks in stable order.
    pub checks: Vec<CheckSchema>,
}

/// OpenAPI schema representation of the RFC 9457 `application/problem+json` error envelope (`R70`, `R71`).
#[derive(Debug, Clone, Serialize, ToSchema)]
#[schema(as = Problem)]
pub struct Problem {
    /// Canonical HTTPS problem-type URI (never `about:blank`).
    #[serde(rename = "type")]
    pub problem_type: String,
    /// Short, human-readable summary of the problem type.
    pub title: String,
    /// HTTP status code generated by the origin server for this occurrence.
    pub status: u16,
    /// Human-readable explanation specific to this occurrence.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
    /// Request path identifying this occurrence (query string stripped).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance: Option<String>,
    /// Stable lowercase snake_case HTTP error code (`R5.13.1`).
    pub code: String,
    /// Stable cross-surface `RSLB###` catalog code (`R67`).
    pub catalog_code: String,
    /// Optional HTTPS documentation URI (`R5.13.4`).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub documentation: Option<String>,
    /// Optional structured per-field validation errors (`R5.15`).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub errors: Option<Vec<FieldError>>,
    /// Optional redacted readiness diagnostics payload emitted by `/readyz` `503` (`R80`).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub diagnostics: Option<DiagnosticsSchema>,
}

/// Root OpenAPI 3.1 metadata and shared component schemas (`R71`).
///
/// Routed operations are merged from [`utoipa_axum::router::OpenApiRouter`] via `split_for_parts()`
/// so router paths and documented paths cannot diverge (`R71` A8).
#[derive(OpenApiDerive)]
#[openapi(
    info(
        title = "rs-launch-blueprint",
        version = "0.0.0",
        description = "Optional HTTP API service for rs-launch-blueprint.",
        license(name = "MIT OR Apache-2.0")
    ),
    tags(
        (name = "ops", description = "Operational liveness and readiness probes"),
        (name = "projects", description = "Project CRUD and cursor-paginated listing")
    ),
    components(schemas(
        Problem,
        FieldError,
        ProjectSchema,
        CreateProjectInputSchema,
        ProjectListResponseSchema,
        LivenessReport,
        LiveStatus,
        DiagnosticsSchema,
        CheckSchema,
        CheckStatusSchema
    ))
)]
pub(crate) struct ApiDoc;

/// Post-process a merged OpenAPI document so every input-taking operation declares a `400`
/// `application/problem+json` response referencing `#/components/schemas/Problem` (`R71` F307).
///
/// Runs on the merged document right after `split_for_parts()` because a `utoipa::Modify` hook on
/// `ApiDoc` runs before `utoipa-axum` merges routed paths (`R71` decision note 2).
pub fn declare_problem_responses(doc: &mut OpenApi) {
    let problem_response = ResponseBuilder::new()
        .description("Bad request or malformed input parameters")
        .content(
            PROBLEM_CONTENT_TYPE,
            ContentBuilder::new()
                .schema(Some(RefOr::Ref(Ref::from_schema_name("Problem"))))
                .build(),
        )
        .build();

    for path_item in doc.paths.paths.values_mut() {
        for op in [
            path_item.get.as_mut(),
            path_item.put.as_mut(),
            path_item.post.as_mut(),
            path_item.delete.as_mut(),
            path_item.options.as_mut(),
            path_item.head.as_mut(),
            path_item.patch.as_mut(),
            path_item.trace.as_mut(),
        ]
        .into_iter()
        .flatten()
        {
            let has_params = op.parameters.as_ref().is_some_and(|p| !p.is_empty());
            let has_body = op.request_body.is_some();
            if has_params || has_body {
                op.responses
                    .responses
                    .entry("400".to_owned())
                    .or_insert_with(|| RefOr::T(problem_response.clone()));
            }
        }
    }
}

/// Serialize `doc` deterministically as pretty-printed JSON terminated by a single newline (`R71`).
#[must_use]
pub fn serialize_openapi(doc: &OpenApi) -> String {
    let mut rendered = serde_json::to_string_pretty(doc).unwrap_or_else(|_| "{}".to_owned());
    rendered.push('\n');
    rendered
}

/// HTTP handler serving the pre-serialized OpenAPI 3.1 JSON document at [`OPENAPI_PATH`].
pub(crate) async fn serve_openapi(
    State((settings, document)): State<(WebSettings, std::sync::Arc<String>)>,
    uri: Uri,
) -> Result<Response, WebError> {
    reject_unsupported_query_params(&uri, &settings.problem_base_uri, false)?;
    Ok((
        StatusCode::OK,
        [
            (
                header::CONTENT_TYPE,
                HeaderValue::from_static("application/json"),
            ),
            (header::CACHE_CONTROL, HeaderValue::from_static("no-cache")),
        ],
        document.as_str().to_owned(),
    )
        .into_response())
}
